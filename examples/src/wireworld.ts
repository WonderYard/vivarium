/* Run */

const canvas = document.getElementById("example-canvas") as HTMLCanvasElement;
canvas.style.imageRendering = "pixelated";

canvas.width = size;
canvas.height = size;

const { evolve, writeCellAt, readGrid } = setup({
  canvas,
  automaton: wireworld,
  initialGrid,
});

// Expose readGrid for convenience
(window as typeof window & { readGrid: () => void }).readGrid = readGrid;

// Click the canvas to put wire elements
canvas.addEventListener("click", (e) => {
  const rect = canvas.getBoundingClientRect();

  // Scale from CSS pixels to grid cells
  const x = Math.floor((e.clientX - rect.left) * (canvas.width / rect.width));
  const y = Math.floor((e.clientY - rect.top) * (canvas.height / rect.height));

  writeCellAt(x, y, wire.index);
});

let skip = false;

const loop = async () => {
  if (!skip) await evolve();
  skip = !skip;

  requestAnimationFrame(loop);
};
requestAnimationFrame(loop);
